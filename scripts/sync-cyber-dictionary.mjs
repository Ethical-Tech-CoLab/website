#!/usr/bin/env node
/**
 * Pull the Cyber Dictionary's terms and library out of the
 * Ethical-Tech-CoLab/cyber-dictionary repo and write them into this site as a
 * typed module, so the printed edition at /print/cyber-dictionary can be
 * typeset from exactly the same entries the live tool serves.
 *
 * Source of truth stays in that repo's terms.js and library.js, which are
 * plain scripts assigning to window.*. They are evaluated here rather than
 * parsed, so a change in their formatting does not break the sync.
 *
 * Usage:
 *   node scripts/sync-cyber-dictionary.mjs
 *   CYBER_DICTIONARY_REPO=/path/to/cyber-dictionary node scripts/sync-cyber-dictionary.mjs
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { homedir } from "node:os";
import vm from "node:vm";

const here = dirname(fileURLToPath(import.meta.url));
const siteRoot = join(here, "..");

const candidates = [
  process.env.CYBER_DICTIONARY_REPO,
  join(siteRoot, "..", "cyber-dictionary"),
  join(homedir(), "cyber-dictionary"),
].filter(Boolean);

const repo = candidates.find((p) => existsSync(join(p, "terms.js")));
if (!repo) {
  console.error(
    "Could not find the cyber-dictionary repo. Tried:\n  " + candidates.join("\n  "),
  );
  process.exit(1);
}

// Both files are browser scripts that assign to window; give them one.
const sandbox = { window: {} };
vm.createContext(sandbox);
for (const file of ["terms.js", "library.js", "cases.js"]) {
  vm.runInContext(readFileSync(join(repo, file), "utf8"), sandbox, { filename: file });
}
const { DOMAINS, TERMS, SHELVES, SOURCES, CASES } = sandbox.window;

for (const [name, value] of Object.entries({ DOMAINS, TERMS, SHELVES, SOURCES, CASES })) {
  if (!Array.isArray(value) || value.length === 0) {
    console.error(`${name} is missing or empty in the source repo.`);
    process.exit(1);
  }
}

// Entries are keyed for terseness in the browser script (t/a/d/def/s, n/o/u/s/w/h/c).
// Spell them out here: this file is read by people laying out pages.
const terms = TERMS.map((e) => ({
  term: e.t,
  alias: e.a ?? "",
  domain: e.d,
  definition: e.def,
  // The other names a term answers to, comma separated. Most terms have none.
  synonyms: e.s ?? "",
}));
const sources = SOURCES.map((e) => ({
  name: e.n,
  operator: e.o,
  url: e.u,
  shelf: e.s,
  what: e.w,
  how: e.h,
  cost: e.c,
}));

const out = `// GENERATED by scripts/sync-cyber-dictionary.mjs — do not edit by hand.
//
// The Cyber Dictionary's ${terms.length} terms and the Library's ${sources.length} sources, copied from
// Ethical-Tech-CoLab/cyber-dictionary. That repo is the source of truth; run
// the sync script again after it changes.

export type DictionaryTerm = {
  term: string;
  /** Expansion or common alias. Empty when the headword needs neither. */
  alias: string;
  domain: string;
  definition: string;
  /** Other names it goes by, comma separated. Empty for most terms. */
  synonyms: string;
};

export type LibrarySource = {
  name: string;
  operator: string;
  url: string;
  shelf: string;
  what: string;
  how: string;
  cost: string;
};

export const dictionaryDomains: string[] = ${JSON.stringify(DOMAINS, null, 2)};

export const dictionaryTerms: DictionaryTerm[] = ${JSON.stringify(terms, null, 2)};

export const libraryShelves: string[] = ${JSON.stringify(SHELVES, null, 2)};

export const librarySources: LibrarySource[] = ${JSON.stringify(sources, null, 2)};

export type CaseStudy = {
  id: string;
  title: string;
  year: string;
  where: string;
  actor: string;
  sector: string;
  kind: string;
  cost: string;
  /** Dictionary headwords this case turns on. Checked at build time upstream. */
  terms: string[];
  /** Each reference carries what the upstream link checker last found. */
  sources: { title: string; url: string; state: string; checked: string }[];
  sections: { heading: string; paragraphs: string[] }[];
};

export const caseStudies: CaseStudy[] = ${JSON.stringify(CASES, null, 2)};

/** A fingerprint of the upstream data, so drift can be detected rather than
 *  discovered. checkCyberDictionarySync() in check-content-invariants.mjs
 *  compares this against the live files. */
export const cyberDictionaryFingerprint = ${JSON.stringify({
  terms: terms.length,
  domains: DOMAINS.length,
  sources: sources.length,
  shelves: SHELVES.length,
  cases: CASES.length,
  syncedAt: new Date().toISOString().slice(0, 10),
}, null, 2)};
`;

const dest = join(siteRoot, "src", "content", "publications", "cyber-dictionary-data.ts");
writeFileSync(dest, out);
console.log(
  `✓ ${terms.length} terms across ${DOMAINS.length} domains, ${sources.length} sources ` +
    `across ${SHELVES.length} shelves, ${CASES.length} case studies ` +
    `→ src/content/publications/cyber-dictionary-data.ts`,
);
